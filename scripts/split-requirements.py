#!/usr/bin/env python3
"""Split REQUIREMENTS.md into verbatim per-phase spec files plus a shared globals file.

Regenerate after every REQUIREMENTS.md change:

    python scripts/split-requirements.py

Output: docs/phase-specs/_shared.md  (global sections, verbatim)
        docs/phase-specs/phase-<N>.md (one per phase, verbatim slices)

Extraction is byte-verbatim — no summarization, no paraphrase. REQUIREMENTS.md
remains the contract; agents read these extracts to stay thin-context and open
the full file only for cross-phase questions.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REQ = ROOT / "REQUIREMENTS.md"
OUT = ROOT / "docs" / "phase-specs"

PHASE_START = re.compile(r"^#{2,3} Phase (\d+(?:\.\d+)?)\b")
CONTAINER = re.compile(r"^## Phases and success criteria")

SHARED_PREAMBLE = (
    "# TFlex — shared requirements (verbatim extract)\n"
    ">\n"
    "> GENERATED by scripts/split-requirements.py from REQUIREMENTS.md — do not edit by hand.\n"
    "> REQUIREMENTS.md remains the contract. For per-phase work read\n"
    "> docs/phase-specs/phase-<N>.md in this folder; open the full REQUIREMENTS.md only\n"
    "> for cross-phase questions.\n"
    "\n"
)

PHASE_PREAMBLE = (
    ">\n"
    "> GENERATED by scripts/split-requirements.py — verbatim extract of the phase below\n"
    "> from REQUIREMENTS.md. Do not edit by hand. Shared rules live in _shared.md (this\n"
    "> folder); REQUIREMENTS.md remains the contract for cross-phase questions.\n"
    "\n"
)


def main():
    text = REQ.read_text(encoding="utf-8")
    lines = text.splitlines(keepends=True)

    # Bucket every line: exactly one of {"global", phase-key, "skip"}.
    buckets = []  # (kind, key, [lines]) in file order; kind "global" or "phase"
    current = None  # (kind, key, lines)

    def ensure(kind, key):
        nonlocal current
        if current is None or current[0] != kind or current[1] != key:
            current = (kind, key, [])
            buckets.append(current)
        return current[2]

    for line in lines:
        m = PHASE_START.match(line)
        if m:
            ensure("phase", m.group(1))
            current[2].append(line)
        elif CONTAINER.match(line):
            current = None  # container heading itself is not emitted
        elif line.startswith("## "):
            ensure("global", "shared")
            current[2].append(line)
        else:
            if current is None:
                # lines before the first heading (shouldn't happen: line 1 is a heading)
                ensure("global", "shared")
            current[2].append(line)

    # Self-check: reassembly must equal the source minus container headings.
    rebuilt = "".join("".join(b[2]) for b in buckets)
    source_minus_container = "".join(
        line for line in lines if not CONTAINER.match(line)
    )
    if rebuilt != source_minus_container:
        sys.exit("FATAL: reassembly check failed — splitting lost or duplicated content")

    # Write outputs.
    OUT.mkdir(parents=True, exist_ok=True)
    for old in OUT.glob("*.md"):
        old.unlink()

    phases = [b for b in buckets if b[0] == "phase"]
    shared = [b for b in buckets if b[0] == "global"]

    seen = set()
    written = []
    for _, key, plines in phases:
        if key in seen:
            sys.exit(f"FATAL: duplicate phase number {key} in REQUIREMENTS.md")
        seen.add(key)
        title = plines[0].strip().lstrip("#").strip()
        preamble = f"# {title}\n" + PHASE_PREAMBLE
        path = OUT / f"phase-{key}.md"
        path.write_text(preamble + "".join(plines), encoding="utf-8")
        written.append((key, path.stat().st_size))

    shared_text = SHARED_PREAMBLE + "".join("".join(b[2]) for b in shared)
    (OUT / "_shared.md").write_text(shared_text, encoding="utf-8")

    def sort_key(item):
        return [int(p) for p in item[0].split(".")]

    print(f"OK: reassembly check passed ({len(lines)} lines, byte-identical)")
    print(f"Wrote _shared.md ({len(shared_text)} bytes)")
    for key, size in sorted(written, key=sort_key):
        print(f"Wrote phase-{key}.md ({size} bytes)")
    print(f"Total: {len(written)} phase files from {REQ.stat().st_size} bytes of REQUIREMENTS.md")


if __name__ == "__main__":
    main()
