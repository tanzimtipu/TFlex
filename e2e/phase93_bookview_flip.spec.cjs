// Records, over the whole burst, the maximum number of simultaneously mounted
// leaves and whether `data-book-stage[data-book-turning]` was ever set with no
// leaf mounted (the Phase 93 invariant forbids both >1 and turning-without-leaf).
async function armRapidWatch() {
  await win.evaluate(() => {
    const state = {
      maxLeaves: 0,
      leafEver: false,
      turningEver: false,
      turningNoLeaf: false,
      stopped: false,
    };
    window.__p93rapid = state;
    const check = () => {
      const s = window.__p93rapid;
      if (s.stopped) return;
      const leaves = document.querySelectorAll('[data-book-turn]').length;
      const stage = document.querySelector('[data-book-stage]');
      const turning = !!(stage && stage.getAttribute('data-book-turning') === 'true');
      if (leaves > s.maxLeaves) s.maxLeaves = leaves;
      if (leaves > 0) s.leafEver = true;
      if (turning) s.turningEver = true;
      if (turning && leaves === 0) s.turningNoLeaf = true;
    };
    const obs = new MutationObserver(check);
    obs.observe(document.querySelector('[data-book-stage]'), {
      subtree: true,
      childList: true,
      attributes: true,
    });
    window.__p93rapidObs = obs;
    const tick = () => {
      check();
      requestAnimationFrame(tick);
    };
    requestAnimationFrame(tick);
  });
}

async function readRapidWatch() {
  return win.evaluate(() => {
    window.__p93rapid.stopped = true;
    if (window.__p93rapidObs) window.__p93rapidObs.disconnect();
    return window.__p93rapid;
  });
}

