  expect(total, 'fixture has fewer than 6 pages').toBeGreaterThanOrEqual(6);

  await useSingle();
  const singleLabel = await progressText();
  expect(singleLabel, 'single-mode progress label').toBe(`Page 1 of ${total}`);
  await useDouble();
  expect(await progressText(), 'double-mode progress label after toggle back').toBe(
    `Page 1-2 of ${total}`,
  );

