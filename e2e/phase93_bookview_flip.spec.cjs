  await win.locator('[aria-label="Book View"]').click();
  await win.waitForFunction(() => window.__p93entry && window.__p93entry.seen, null, {
    timeout: 8000,
  });
  const entry = await win.evaluate(() => window.__p93entry);
  await win.waitForSelector('[data-book-view]', { state: 'visible', timeout: 15000 });
  await win.waitForTimeout(500);

  // Progress label + single/double toggle. A plain PDF opens in SINGLE layout,
  // so establish double through the real toggle first.
  await useDouble();
  const doubleLabel = await progressText();
