// ---------------------------------------------------------------------------
// Spine-join capture. The turning leaf hinges at its spine edge (transform-
// origin left for a next turn, right for a prev turn), so that edge must stay
// pinned to the crease seam across the whole swing - no gap, no overlap pop.
// Samples the leaf rect and the crease rect every rAF tick while the leaf is
// mounted.
// ---------------------------------------------------------------------------
async function armSpineCapture() {
  await win.evaluate(() => {
    const state = { started: false, done: false, samples: [] };
    window.__p93spine = state;
    const tick = (now) => {
      const s = window.__p93spine;
      if (s.done) return;
      const leaf = document.querySelector('[data-book-turn]');
      const crease = document.querySelector('[data-book-crease]');
      if (s.started && leaf && crease) {
        // The spine edge is the element's transform-origin edge. `getBounding
        // -ClientRect` of a 3D-rotated figure swaps its projected edges once
        // the swing passes 90deg, so it cannot identify the hinge. Read the
        // UNtransformed layout box (offsetParent rect + offsetLeft) and add the
        // element-local transform-origin x to resolve the hinge in page coords.
        const cs = getComputedStyle(leaf);
        const oxRaw = cs.transformOrigin.split(' ')[0];
        const originX = oxRaw.endsWith('%')
          ? (parseFloat(oxRaw) / 100) * leaf.offsetWidth
          : parseFloat(oxRaw);
        const op = leaf.offsetParent;
        const baseLeft = op ? op.getBoundingClientRect().left : 0;
        const hingeX = baseLeft + leaf.offsetLeft + originX;
        const cr = crease.getBoundingClientRect();
        s.samples.push({
          t: Math.round(now),
          hingeX: Math.round(hingeX * 100) / 100,
          originX: Math.round(originX * 100) / 100,
          offsetLeft: leaf.offsetLeft,
          offsetWidth: leaf.offsetWidth,
          transformOrigin: cs.transformOrigin,
          creaseLeft: Math.round(cr.left * 100) / 100,
          creaseRight: Math.round(cr.right * 100) / 100,
          creaseCenter: Math.round(((cr.left + cr.right) / 2) * 100) / 100,
          pages: Array.from(document.querySelectorAll('[data-book-page]')).map((el) =>
            el.getAttribute('data-book-page'),
          ),
        });
      }
      if (s.started && !leaf && s.samples.length > 0) {
        s.done = true;
        return;
      }
      requestAnimationFrame(tick);
    };
    requestAnimationFrame(tick);
  });
}

