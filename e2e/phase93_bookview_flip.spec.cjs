// Pause the in-flight leaf's CSS animation at a deterministic offset so a
// mid-swing screenshot cannot race the settle, then resume it.
async function pauseTurnAnim(ms) {
  return win.evaluate((at) => {
    const l = document.querySelector('[data-book-turn]');
    if (!l) return { ok: false, reason: 'no leaf' };
    const anims = l.getAnimations();
    if (!anims.length) return { ok: false, reason: 'no animation' };
    anims.forEach((a) => {
      a.pause();
      a.currentTime = at;
    });
    return { ok: true, n: anims.length, transform: getComputedStyle(l).transform };
  }, ms);
}

async function resumeTurnAnim() {
  await win.evaluate(() => {
    const l = document.querySelector('[data-book-turn]');
    if (l) l.getAnimations().forEach((a) => a.play());
  });
}

