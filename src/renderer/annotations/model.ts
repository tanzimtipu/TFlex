// Annotation domain model for the renderer.
//
// All geometry is stored in PAGE POINTS with a TOP-LEFT origin at scale 1
// (i.e. CSS-like coordinates relative to the unrotated page). The overlay
// multiplies by the current cssScale to position elements, so annotations
// stay aligned at every zoom level. The backend converts to the PDF's
// bottom-left coordinate space when serializing /Annots.

// ---------------------------------------------------------------------------
// Geometry primitives (page points, top-left origin)

export interface PagePoint {
  x: number;
  y: number;
}

export interface PageRect {
  x: number;
  y: number;
  width: number;
  height: number;
}

// ---------------------------------------------------------------------------
// Colors

/** Built-in annotation colors. The user can also pick any custom hex
 *  through the ColorPalette; that path produces a free-form hex string
 *  instead of one of these literals. The `hexOrBuiltIn` alias is the
 *  union shape used everywhere annotations touch the color channel. */
export type AnnotationColor =
  | "yellow"
  | "red"
  | "green"
  | "blue"
  | "orange"
  | "pink"
  | "purple"
  | "teal"
  | "gray";

/** Any valid color for an annotation: either a built-in name or a
 *  hex string (#rgb / #rrggbb, normalised to lowercase). Custom
 *  hexes are stored verbatim and resolved to a CSS color by the
 *  overlay at render time. */
export type AnnotationColorValue = AnnotationColor | string;

/** Built-in palette (Phase 13 — was 4 names, now 9). The original four
 *  names stay at the front so any annotation persisted against an
 *  older renderer keeps resolving to the same hex; the five new names
 *  slot in after for a richer toolbar picker. Order is the visual
 *  reading order in the toolbar's quick swatch row (warm -> cool ->
 *  accent). */
export const ANNOTATION_COLORS: readonly AnnotationColor[] = [
  "yellow",
  "orange",
  "red",
  "pink",
  "purple",
  "teal",
  "green",
  "blue",
  "gray",
];

export const ANNOTATION_COLOR_HEX: Record<AnnotationColor, string> = {
  yellow: "#eab308",
  orange: "#f97316",
  red: "#ef4444",
  pink: "#ec4899",
  purple: "#a855f7",
  teal: "#14b8a6",
  green: "#22c55e",
  blue: "#3b82f6",
  gray: "#64748b",
};

/** Resolve any annotation color value (built-in name OR raw hex) to a
 *  CSS color string. Unknown values fall through to `currentColor`,
 *  which lets the overlay degrade gracefully instead of painting
 *  nothing — the worst case is "the highlight isn't visible," not
 *  a crash. */
export function annotationColorToCss(value: AnnotationColorValue): string {
  if (typeof value !== "string") return "currentColor";
  if (value in ANNOTATION_COLOR_HEX) {
    return ANNOTATION_COLOR_HEX[value as AnnotationColor];
  }
  // Custom hex (lowercase, with leading #, length 4 or 7).
  if (/^#[0-9a-f]{3}$/.test(value) || /^#[0-9a-f]{6}$/.test(value)) {
    return value;
  }
  return "currentColor";
}

export function isAnnotationColor(v: unknown): v is AnnotationColor {
  if (typeof v !== "string") return false;
  return v in ANNOTATION_COLOR_HEX;
}

// ---------------------------------------------------------------------------
// Annotations

export type MarkupKind = "highlight" | "underline" | "strikeout";
export type ShapeKind = "rect" | "ellipse";

export type AnnotationKind =
  | MarkupKind
  | "ink"
  | "textbox"
  | ShapeKind
  | "arrow"
  | "note"
  | "callout";

interface AnnotationBase {
  /** Stable id, generated by the renderer (crypto.randomUUID) at creation. */
  id: string;
  /** 1-based page number in the document's current visible order. */
  page: number;
  color: AnnotationColorValue;
  createdAt: string; // ISO 8601
}

/** Text markup: highlight / underline / strikeout anchored to text quads
 *  (one rect per covered line). `text` is a snapshot of the covered text,
 *  used as the preview label in the annotations panel. */
export interface MarkupAnnotation extends AnnotationBase {
  kind: MarkupKind;
  rects: PageRect[];
  text: string;
}

/** Freehand pen stroke. `width` is the stroke width in page points. */
export interface InkAnnotation extends AnnotationBase {
  kind: "ink";
  points: PagePoint[];
  width: number;
}

/** Free-floating text box placed by a click. */
export interface TextBoxAnnotation extends AnnotationBase {
  kind: "textbox";
  rect: PageRect;
  text: string;
}

/** Rectangle or ellipse, defined by its bounding box (drag from-to). */
export interface ShapeAnnotation extends AnnotationBase {
  kind: ShapeKind;
  rect: PageRect;
}

/** Arrow from one point to another (drag direction is preserved). */
export interface ArrowAnnotation extends AnnotationBase {
  kind: "arrow";
  from: PagePoint;
  to: PagePoint;
}

/** Sticky note anchored to a page location, with editable content. */
export interface NoteAnnotation extends AnnotationBase {
  kind: "note";
  at: PagePoint;
  text: string;
}

/** Phase 12 — callout (text box with an arrow to an anchor point).
 *  `rect` is the text-box bounding box in page points (top-left
 *  origin). `at` is the point the arrow points AT — the "subject"
 *  the callout is annotating. The arrow is rendered as a thin
 *  stroked line from `rect`'s nearest edge to `at`, with a small
 *  arrowhead at `at` so the reader can see what the callout refers
 *  to. `text` is the editable content of the box. Wire-shape
 *  matching uses the same `rect` (renderer) / `rects[0]` (engine)
 *  convention as the textbox / shape annotations. */
export interface CalloutAnnotation extends AnnotationBase {
  kind: "callout";
  rect: PageRect;
  at: PagePoint;
  text: string;
}

export type Annotation =
  | MarkupAnnotation
  | InkAnnotation
  | TextBoxAnnotation
  | ShapeAnnotation
  | ArrowAnnotation
  | NoteAnnotation
  | CalloutAnnotation;

/** Fields the user can change after creation (via the annotations panel or
 *  the inline note editor). `color` accepts both built-in names and free-form
 *  hex strings so the picker can apply custom colors. */
export interface AnnotationPatch {
  color?: AnnotationColorValue;
  text?: string;
}

/** Apply a patch to an annotation. Returns the same object when the patch
 *  is empty or inapplicable (color applies to all kinds; text applies to
 *  markup snapshots, text boxes, notes and callouts). */
export function applyPatch(ann: Annotation, patch: AnnotationPatch): Annotation {
  let next = ann;
  if (patch.color !== undefined && patch.color !== ann.color) {
    next = { ...next, color: patch.color };
  }
  if (
    patch.text !== undefined &&
    (next.kind === "textbox" ||
      next.kind === "note" ||
      next.kind === "callout" ||
      isMarkup(next)) &&
    patch.text !== next.text
  ) {
    next = { ...next, text: patch.text };
  }
  return next;
}

export function isMarkup(a: Annotation): a is MarkupAnnotation {
  return (
    a.kind === "highlight" || a.kind === "underline" || a.kind === "strikeout"
  );
}

// ---------------------------------------------------------------------------
// Tool state

/** The active annotation tool. "select" means no annotation tool: the page
 *  behaves as a plain viewer (text selection, scrolling). */
export type AnnotationTool =
  | "select"
  | MarkupKind
  | "ink"
  | "textbox"
  | ShapeKind
  | "arrow"
  | "note"
  | "callout";

export interface AnnotationToolState {
  tool: AnnotationTool;
  color: AnnotationColorValue;
  /** Pen stroke width in page points. */
  penWidth: number;
}

export const PEN_WIDTHS: readonly number[] = [1.5, 3, 5];

/** Default accent color for the highlight / markup tools, in the
 *  renderer CSS `#rrggbb` form. Per REQUIREMENTS.md the product
 *  ships with `#2563eb` (blue 600) as its single accent. The
 *  markup / ink default used to be the built-in `"yellow"` name
 *  (which resolves to `#eab308`), but the visual identity of the
 *  app is centred on the blue accent and the highlight swatch
 *  should reflect that — a blue highlight reads as "this is the
 *  default selection colour" the moment the user arms the tool,
 *  while a yellow swatch looks like a leftover from a different
 *  product. The custom-hex default flows through
 *  `annotationColorToCss` exactly like a built-in name would, so
 *  the overlay, the swatch, and the panel preview all agree. */
export const DEFAULT_ANNOTATION_COLOR = "#2563eb";

export const initialAnnotationToolState: AnnotationToolState = {
  tool: "select",
  color: DEFAULT_ANNOTATION_COLOR,
  penWidth: PEN_WIDTHS[1],
};

export type AnnotationToolAction =
  | { type: "set-tool"; tool: AnnotationTool }
  | { type: "set-color"; color: AnnotationColorValue }
  | { type: "set-pen-width"; width: number };

/** One active tool at a time. `set-tool` sets the tool exactly; tool
 *  buttons use `toggleTool` so clicking the active tool returns to plain
 *  selection mode. */
export function annotationToolReducer(
  state: AnnotationToolState,
  action: AnnotationToolAction,
): AnnotationToolState {
  switch (action.type) {
    case "set-tool":
      return { ...state, tool: action.tool };
    case "set-color":
      return { ...state, color: action.color };
    case "set-pen-width":
      return action.width > 0 ? { ...state, penWidth: action.width } : state;
  }
}

/** The tool that should become active when the user clicks the button for
 *  `tool`: clicking the active tool deactivates it (back to "select"). */
export function toggleTool(
  state: AnnotationToolState,
  tool: AnnotationTool,
): AnnotationTool {
  return state.tool === tool ? "select" : tool;
}

// ---------------------------------------------------------------------------
// Panel helpers

/** Sort annotations for the panel: by page, then by creation time. The
 *  input array is not mutated. */
export function sortAnnotations(list: readonly Annotation[]): Annotation[] {
  return [...list].sort((a, b) => {
    if (a.page !== b.page) return a.page - b.page;
    if (a.createdAt !== b.createdAt) return a.createdAt < b.createdAt ? -1 : 1;
    return a.id < b.id ? -1 : a.id > b.id ? 1 : 0;
  });
}

export function kindLabel(kind: AnnotationKind): string {
  switch (kind) {
    case "highlight":
      return "Highlight";
    case "underline":
      return "Underline";
    case "strikeout":
      return "Strikethrough";
    case "ink":
      return "Pen stroke";
    case "textbox":
      return "Text box";
    case "rect":
      return "Rectangle";
    case "ellipse":
      return "Ellipse";
    case "arrow":
      return "Arrow";
    case "note":
      return "Note";
    case "callout":
      return "Callout";
  }
}

/** Short preview text for a panel row. */
export function annotationSummary(a: Annotation): string {
  switch (a.kind) {
    case "highlight":
    case "underline":
    case "strikeout":
    case "textbox":
    case "note":
    case "callout":
      return a.text.trim().length > 0 ? a.text : kindLabel(a.kind);
    default:
      return kindLabel(a.kind);
  }
}

/** Whether the annotation carries user-editable text content (shown as a
 *  textarea in the panel's expanded row). */
export function hasEditableText(a: Annotation): boolean {
  return a.kind === "textbox" || a.kind === "note" || a.kind === "callout";
}

/** Per-kind counts, for diagnostics. */
export function countByKind(
  list: readonly Annotation[],
): Record<AnnotationKind, number> {
  const counts: Record<AnnotationKind, number> = {
    highlight: 0,
    underline: 0,
    strikeout: 0,
    ink: 0,
    textbox: 0,
    rect: 0,
    ellipse: 0,
    arrow: 0,
    note: 0,
    callout: 0,
  };
  for (const a of list) {
    counts[a.kind] += 1;
  }
  return counts;
}
