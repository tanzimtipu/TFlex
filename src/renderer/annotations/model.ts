// Annotation domain model for the renderer.
//
// All geometry is stored in PAGE POINTS with a TOP-LEFT origin at scale 1
// (i.e. CSS-like coordinates relative to the unrotated page). The overlay
// multiplies by the current cssScale to position elements, so annotations
// stay aligned at every zoom level. The backend converts to the PDF's
// bottom-left coordinate space when serializing /Annots.

import type { AnnRect, AnnTextStyle } from "../../shared/types";
import { ANNOTATION_COLOR_NAMES } from "../../shared/annotationColors";

// ---------------------------------------------------------------------------
// Geometry primitives (page points, top-left origin)

export interface PagePoint {
  x: number;
  y: number;
}

export interface PageRect {
  x: number;
  y: number;
  width: number;
  height: number;
}

// ---------------------------------------------------------------------------
// Colors

/** Built-in annotation colors. The canonical name set lives in the shared
 *  module `src/shared/annotationColors.ts` (DEF-260) and is the same list the
 *  PDF engine consumes, so the renderer can never drift from the engine's
 *  accepted named colours. The user can also pick any custom hex through the
 *  ColorPalette; that path produces a free-form hex string instead of one of
 *  these literals. The `AnnotationColorValue` alias is the union shape used
 *  everywhere annotations touch the color channel. */
export type AnnotationColor = (typeof ANNOTATION_COLOR_NAMES)[number];

/** Any valid color for an annotation: either a built-in name or a
 *  hex string (#rgb / #rrggbb, normalised to lowercase). Custom
 *  hexes are stored verbatim and resolved to a CSS color by the
 *  overlay at render time. */
export type AnnotationColorValue = AnnotationColor | string;

/** Built-in palette, in the canonical shared order: the nine historic engine
 *  presets followed by the DEF-260 additions. Order is the toolbar's quick
 *  swatch row reading order; membership comes from the shared list. */
export const ANNOTATION_COLORS: readonly AnnotationColor[] = ANNOTATION_COLOR_NAMES;

export const ANNOTATION_COLOR_HEX: Record<AnnotationColor, string> = {
  yellow: "#eab308",
  orange: "#f97316",
  red: "#ef4444",
  pink: "#ec4899",
  purple: "#a855f7",
  teal: "#14b8a6",
  green: "#22c55e",
  blue: "#3b82f6",
  gray: "#64748b",
  cyan: "#00ffff",
  magenta: "#ff00ff",
  white: "#ffffff",
};

/** Resolve any annotation color value (built-in name OR raw hex) to a
 *  CSS color string. Unknown values fall through to `currentColor`,
 *  which lets the overlay degrade gracefully instead of painting
 *  nothing — the worst case is "the highlight isn't visible," not
 *  a crash.
 *
 *  Custom hexes may come from older persisted presets (a custom hex
 *  written before the picker normalised to lowercase, a saved
 *  preset round-tripped through main and back, or a value the user
 *  hand-typed in DevTools). We accept any case (#RGB, #RrGgBb) and
 *  length (3 or 6), expand 3-digit shorthand, then return a clean
 *  lowercase hex so every consumer sees the same canonical form.
 *  Returning the normalised hex (instead of the input verbatim) also
 *  means the overlay's paint path never has to care about case —
 *  older round-trips can't paint a different shade just because
 *  someone wrote `#FF0000` once. */
export function annotationColorToCss(value: AnnotationColorValue): string {
  if (typeof value !== "string") return "currentColor";
  if (value in ANNOTATION_COLOR_HEX) {
    return ANNOTATION_COLOR_HEX[value as AnnotationColor];
  }
  // Custom hex — accept any case + length, normalise to #rrggbb.
  // The picker normally produces lowercase, but we never want a
  // stale / legacy / hand-typed uppercase hex to fall through to
  // `currentColor` and leave the highlight invisible. The 3-digit
  // shorthand (#rgb -> #rrggbb) is expanded for completeness so a
  // user who typed `#0f0` ends up with the same green as `#00ff00`.
  const m = /^#?([0-9a-fA-F]{3}|[0-9a-fA-F]{6})$/.exec(value.trim());
  if (m === null) return "currentColor";
  const raw = m[1];
  if (raw === undefined) return "currentColor";
  if (raw.length === 3) {
    const r = raw[0];
    const g = raw[1];
    const b = raw[2];
    if (r === undefined || g === undefined || b === undefined) return "currentColor";
    return `#${r}${r}${g}${g}${b}${b}`.toLowerCase();
  }
  return `#${raw}`.toLowerCase();
}

export function isAnnotationColor(v: unknown): v is AnnotationColor {
  if (typeof v !== "string") return false;
  return v in ANNOTATION_COLOR_HEX;
}

// ---------------------------------------------------------------------------
// Annotations

export type MarkupKind = "highlight" | "underline" | "strikeout";
export type ShapeKind = "rect" | "ellipse";

export type AnnotationKind =
  | MarkupKind
  | "ink"
  | "textbox"
  | ShapeKind
  | "arrow"
  | "note"
  | "callout";

interface AnnotationBase {
  /** Stable id, generated by the renderer (crypto.randomUUID) at creation. */
  id: string;
  /** 1-based page number in the document's current visible order. */
  page: number;
  color: AnnotationColorValue;
  createdAt: string; // ISO 8601
  /** Phase 24 — the stored text style for the text-bearing kinds (textbox /
   *  callout / note). Mirrors the shared `AnnModel.style` (`AnnTextStyle`)
   *  so a value read off an engine echo, a panel patch, or a create payload
   *  is the same shape everywhere. Absent means the legacy appearance:
   *  Helvetica 12, left-aligned, 1.35 line step, no highlight/list/indent.
   *  The engine bakes the same fields into the /AP stream at save time. */
  style?: AnnTextStyle;
}

/** Text markup: highlight / underline / strikeout anchored to text quads
 *  (one rect per covered line). `text` is a snapshot of the covered text,
 *  used as the preview label in the annotations panel. */
export interface MarkupAnnotation extends AnnotationBase {
  kind: MarkupKind;
  rects: PageRect[];
  text: string;
}

/** Freehand pen stroke. `width` is the stroke width in page points. */
export interface InkAnnotation extends AnnotationBase {
  kind: "ink";
  points: PagePoint[];
  width: number;
}

/** Free-floating text box placed by a click. */
export interface TextBoxAnnotation extends AnnotationBase {
  kind: "textbox";
  rect: PageRect;
  text: string;
}

/** Rectangle or ellipse, defined by its bounding box (drag from-to). */
export interface ShapeAnnotation extends AnnotationBase {
  kind: ShapeKind;
  rect: PageRect;
}

/** Arrow from one point to another (drag direction is preserved). */
export interface ArrowAnnotation extends AnnotationBase {
  kind: "arrow";
  from: PagePoint;
  to: PagePoint;
}

/** Sticky note anchored to a page location, with editable content. */
export interface NoteAnnotation extends AnnotationBase {
  kind: "note";
  at: PagePoint;
  text: string;
}

/** Phase 12 — callout (text box with an arrow to an anchor point).
 *  `rect` is the text-box bounding box in page points (top-left
 *  origin). `at` is the point the arrow points AT — the "subject"
 *  the callout is annotating. The arrow is rendered as a thin
 *  stroked line from `rect`'s nearest edge to `at`, with a small
 *  arrowhead at `at` so the reader can see what the callout refers
 *  to. `text` is the editable content of the box. Wire-shape
 *  matching uses the same `rect` (renderer) / `rects[0]` (engine)
 *  convention as the textbox / shape annotations. */
export interface CalloutAnnotation extends AnnotationBase {
  kind: "callout";
  rect: PageRect;
  at: PagePoint;
  text: string;
}

export type Annotation =
  | MarkupAnnotation
  | InkAnnotation
  | TextBoxAnnotation
  | ShapeAnnotation
  | ArrowAnnotation
  | NoteAnnotation
  | CalloutAnnotation;

